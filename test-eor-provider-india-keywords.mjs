import assert from 'node:assert/strict';
import fs from 'node:fs';
import seed from './eor-provider-india-keywords.js';
assert.equal(seed.REVISION,'eor-provider-india-keywords-v1');
assert.equal(seed.records.length,40);
assert.equal(seed.records.filter(row=>row.comparison).length,19);
assert.equal(seed.records.filter(row=>!row.comparison).length,21);
assert.equal(seed.keywordRows().length,40);
assert(seed.keywordRows().every(row=>row.country==='in'));
assert.equal(seed.records.find(row=>row.keyword==='rippling pricing').volume,1500);
assert.equal(seed.records.find(row=>row.keyword==='rippling vs deel').volume,600);
assert.equal(seed.matchesBoard(['Other','EOR provider India']),true);
assert.equal(seed.matchesBoard(['Other']),false);
let n=0;
const content={views:{competitor:{rows:[],types:[],cells:{},comparisonCells:{}}}};
const db=seed.keywordRows().map((row,index)=>({...row,id:'kw-'+index}));
assert.equal(seed.apply(content,db,()=>'id-'+(++n),{type:'competitor',aw:'Competitor aware'}),true);
const matrix=content.views.competitor;
assert.equal(matrix.rows.filter(row=>row.name).length,8);
assert.deepEqual(matrix.types.map(type=>type.name),['Alternatives','Reviews','Pricing','Features']);
assert.equal(Object.keys(matrix.cells).length,21);
assert.equal(Object.keys(matrix.comparisonCells).length,19);
assert(Object.values(matrix.cells).every(cell=>cell.st==='for_review'&&cell.type==='competitor'&&cell.kws.length===1));
assert(Object.values(matrix.comparisonCells).every(cell=>cell.st==='for_review'&&cell.aw==='Competitor aware'&&cell.kws.length===1));
assert.equal(seed.apply(content,db,()=>'unused',{type:'competitor',aw:'Competitor aware'}),false);
assert.equal(Object.keys(matrix.cells).length,21);
assert.equal(Object.keys(matrix.comparisonCells).length,19);
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
assert(html.includes('<script src="eor-provider-india-keywords.js"></script>'));
assert(html.includes('await ensureEorProviderIndiaKeywordSeed();'));
assert(html.includes("api.keywordRows(), 'eor-provider-india-screenshots'"));console.log('PASS: EOR provider India maps 21 competitor terms and 19 pairwise terms without duplicates.');
