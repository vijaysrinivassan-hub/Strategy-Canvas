import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
let id=0;
const ctx=vm.createContext({uid:()=>String(++id),document:{},confirm:()=>true});
vm.runInContext(fs.readFileSync('icp-cell-canvas.js','utf8')+'\nglobalThis.canvasApi=IcpCellCanvas;',ctx);
const api=ctx.canvasApi,legacy={id:'a',text:'Legacy stage',selected:false};
assert.equal(api.ensure(legacy).nodes.length,1);
assert.equal(api.width(legacy),216);
api.add(legacy);assert.equal(legacy.canvas.nodes.length,2);assert.ok(api.width(legacy)>350);
legacy.canvas.nodes[1].text='Parallel work';api.sync(legacy);assert.match(legacy.text,/Parallel branch: Parallel work/);
api.remove(legacy,legacy.canvas.nodes[0].id);assert.equal(legacy.text,'Parallel work');
const m=require('./tools/rebuild-icp-cell-canvases.cjs'),layouts=require('./tools/ai-data-technology-canvas-layouts.json');
const PRODUCT=m.PRODUCT,TAB=m.TAB,p={icpChoices:{columns:{}},icps:[],selectedIcp:'',icpTableColumns:{technology:['useCases']},icpNestedColumns:{technology:{useCases:layouts.map(x=>({id:x.id,name:x.id}))}}};
for(const x of layouts)p.icpChoices.columns[JSON.stringify(['technology',JSON.stringify(['useCases',x.id])])]=[{id:'old-'+x.id,text:'old',selected:false}];
p.icpChoices.columns[JSON.stringify(['input','maturity'])]=[{id:'data',text:'Data',selected:false}];
const b={client:'AI Data Platform',workspaceProductId:PRODUCT,tabs:{[TAB]:{positioning:p,aiPrompt:'Prior instructions'}},productWorkspaces:{[PRODUCT]:{tabs:{}}}};
const result=m.migrate(b);assert.deepEqual(result,{changed:true,cells:25,nodes:31,branchedCells:6});
assert.equal(m.migrate(b).changed,false);
const get=id=>p.icpChoices.columns[JSON.stringify(['technology',JSON.stringify(['useCases',id])])];
assert.deepEqual(get('retention-planning').map(x=>x.canvas.nodes.length),[1,2,1]);
assert.deepEqual(get('inventory-management').map(x=>x.canvas.nodes.length),[1,1,2,1,2,1,1]);
assert.equal(get('campaign-budget-planning').every(x=>x.canvas.nodes.length===1),true);
assert.equal(Object.values(p.icpChoices.columns).flat().some(x=>x.selected),false);
assert.equal(b.tabs[TAB].icpCellCanvasArchive.technologyChoices[JSON.stringify(['technology',JSON.stringify(['useCases','retention-planning'])])][0].text,'old');
assert.deepEqual(b.tabs[TAB],b.productWorkspaces[PRODUCT].tabs[TAB]);
console.log('PASS: legacy conversion, node add/remove, dynamic width, six branched stages, linear-stage preservation, archive and idempotence.');
