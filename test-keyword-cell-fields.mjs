import fs from 'node:fs';import vm from 'node:vm';import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const ctx=vm.createContext({});
vm.runInContext(html.slice(html.indexOf('function cellState('),html.indexOf('/* What a matrix cell catches')),ctx);
vm.runInContext(html.slice(html.indexOf('function cellOf('),html.indexOf('function renderArticleTypes(')),ctx);
const m={cells:{legacy:true}};
assert.equal(ctx.cellState(m,'legacy',{}).on,true);
ctx.setCellState(m,'a',{url:'/payroll',writtenBy:'old',mode:'aeo'});
let c=ctx.cellState(m,'a');assert.equal(c.url,'/payroll');assert.equal(c.writtenBy,'old');
ctx.setCellState(m,'a',{...c,v:'New title',st:'written'});
c=ctx.cellState(JSON.parse(JSON.stringify(m)),'a');assert.equal(c.url,'/payroll');assert.equal(c.writtenBy,'old');
const row={cells:{legacy:'Legacy title'}};
assert.equal(ctx.cellOf(row,'legacy',{}).v,'Legacy title');
ctx.setCellIn(row,'a',{url:'payroll-guide',writtenBy:'new'},{});
ctx.setCellIn(row,'a',{v:'Payroll guide',aw:'Solution aware'},{});
c=ctx.cellOf(JSON.parse(JSON.stringify(row)),'a',{});
assert.equal(c.url,'payroll-guide');assert.equal(c.writtenBy,'new');assert.equal(c.v,'Payroll guide');
assert.equal(ctx.cellQuiet({url:'slug'},0),false);assert.equal(ctx.cellQuiet({writtenBy:'old'},0),false);
ctx.setCellIn(row,'a',{url:'',writtenBy:''},{});assert.equal(ctx.cellOf(row,'a',{}).writtenBy,'');
assert.equal((html.match(/inp.placeholder = 'title'/g)||[]).length,2);
assert(html.includes("url.placeholder = 'slug'"));
assert(html.includes("[['','Written by'],['old','Old'],['new','New']]"));
assert(html.includes("foot2.append(writtenBy)"));
assert(html.includes("td.insertBefore(urlRow, td.querySelector(':scope > .gr-kws'))"));
console.log('PASS: URL and Written by persist through edits and reload, legacy cells preserved, clearing supported, title/slug placeholders and shared layout wiring.');
