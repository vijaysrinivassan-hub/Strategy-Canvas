import assert from 'node:assert/strict';
import fs from 'node:fs';
const tool=fs.readFileSync(new URL('./mcp-server/src/tools/onboarding-market-map.ts',import.meta.url),'utf8');
const index=fs.readFileSync(new URL('./mcp-server/src/index.ts',import.meta.url),'utf8');
const flow=fs.readFileSync(new URL('./onboarding-flow.js',import.meta.url),'utf8');
const prompts=JSON.parse(fs.readFileSync(new URL('./ai-prompts.json',import.meta.url),'utf8'));
assert(index.includes('registerOnboardingMarketMapTools(server);'));
for (const name of ['onboarding_market_map_get','onboarding_market_map_set']) assert(tool.includes("registerTool('"+name+"'"));
assert(tool.includes("const TAB = 'Strategy 1 — Brand Strategy'"));
assert(tool.includes("if(row.updated_at!==revision)throw new ToolError('Board changed. Read it again before saving.');"));
assert(tool.includes("key:(code||'any')+'|'+(size||'any')"), 'segment keys match obfSegments');
assert(flow.includes("key:(code||'any')+'|'+(size||'any')"), 'the browser still builds the same segment keys');
assert(flow.includes("source:'you'"), 'client drags are saved as source you');
assert(tool.includes("x:z.number().min(0).max(1),y:z.number().min(0).max(1)"), 'positions are validated to 0..1');
assert(tool.includes("source:'ai'"), 'AI placements are marked as placed by the AI');
assert(tool.includes("next[position.key]?.source==='you'&&!override_client"), 'client-placed dots are skipped unless overridden');
assert(tool.includes("Unknown segment keys"), 'keys must be current segments');
assert(tool.includes("if(workspace?.tabs?.[TAB])writePositions(workspace.tabs[TAB],next);"), 'any workspace copy moves with the live tab');
const prompt=prompts.gtm_strategy_seo.prompt;
assert(prompt.includes('MARKET MAP') && prompt.includes('onboarding_market_map_get') && prompt.includes('onboarding_market_map_set'));
assert(prompt.includes('Never move a dot the client placed'));
console.log('PASS: Onboarding Market map MCP tools read segments and place dots as the AI, never over the client’s own placements.');
