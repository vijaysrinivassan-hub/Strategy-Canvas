import assert from 'node:assert/strict';
import K from './keyword-columns.js';
import M from './keyword-slug-migration.cjs';
const config=K.ensurePageViews(K.seed());
assert.equal(Object.values(config.pageViews).flatMap(Object.values).length,9);
config.pageViews.category.listicle[0].name='Listicle category';
const root={views:{category:{kind:'grid',columns:[{id:'old',name:'Category name'}],rows:[{id:'r',pageGroup:'listicle',cells:{old:{v:'slug',kws:['k']}}}]}}};
K.sync(root,config);
assert.equal(root.views.category.pageColumns.listicle[0].name,'Listicle category');
assert.equal(root.views.category.pageColumns.informational[0].name,'Category name');
const l=K.pageView(root.views.category,'listicle'),i=K.pageView(root.views.category,'informational');
const oldOrder=i.columns.map(c=>c.id);
K.move(l,l.columns[0].id,1);assert.deepEqual(i.columns.map(c=>c.id),oldOrder);
assert.equal(root.views.category.rows[0].cells.old.kws[0],'k');
const a={v:'payroll-software',url:'',kws:['k'],on:true,type:'t',aw:'aware',st:'selected'};
const comparison={v:'A vs B',url:'',kws:['c']};
const body={tabs:{content:{views:{category:{rows:[{id:'r',cells:{a,b:{v:'A real article title'},c:{v:'clash',url:'keep-me'}}}]},competitor:{cells:{x:{v:'hr',kws:['x']}},comparisonCells:{pair:comparison}}}}}};
const result=M.moveSlugs(body);assert.deepEqual(result,{moved:2,conflicts:1});
assert.equal(a.url,'payroll-software');assert.equal(a.v,'');assert.deepEqual(a.kws,['k']);assert.equal(a.st,'selected');
assert.equal(comparison.v,'A vs B');
assert.deepEqual(M.moveSlugs(body),{moved:0,conflicts:1});
console.log('PASS: nine independent universal templates, per-table order, field-only slug moves, conflict safety, comparison exclusion and idempotence.');
