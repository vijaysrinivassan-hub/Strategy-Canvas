import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const asset=JSON.parse(fs.readFileSync(new URL('./competitive-intelligence-classifications.json',import.meta.url),'utf8'));
const saras=asset.profiles.find(profile=>profile.id==='saras-analytics');
assert(saras);
assert.equal(saras.urls.length,770);
assert.equal(new Set(saras.urls).size,770);
assert.deepEqual(saras.sitemaps,['https://www.sarasanalytics.com/sitemap.xml']);
assert(saras.urls.every(url=>url==='https://www.sarasanalytics.com'||url.startsWith('https://www.sarasanalytics.com/')));

const records=Object.entries(asset.classifications).filter(([,meta])=>meta.workspace==='ai-data-platform');
assert.equal(records.length,770);
assert.equal(records.filter(([,meta])=>meta.section==='Corporate & Non-SEO').length,12);
assert(records.every(([,meta])=>meta.awareness&&meta.topicGroup&&meta.topic));
assert(records.filter(([,meta])=>meta.section!=='Corporate & Non-SEO').every(([,meta])=>/^(ICP|Value|Competitor) (SEO|AEO)$/.test(meta.section)));
assert(records.filter(([,meta])=>meta.section!=='Corporate & Non-SEO').every(([,meta])=>['problem-unaware','problem-aware','solution-aware','competitor-aware'].includes(meta.awareness)));
assert.equal(records.filter(([,meta])=>meta.section==='Competitor AEO').length,42);
assert.equal(new Set(records.filter(([,meta])=>meta.section==='Competitor AEO').map(([,meta])=>meta.hierarchy)).size,23);
const icpSeo=records.filter(([,meta])=>meta.section==='ICP SEO');
assert.equal(icpSeo.length,365);
assert.equal(icpSeo.filter(([,meta])=>meta.awareness==='problem-unaware').length,9);
assert.equal(icpSeo.filter(([,meta])=>meta.awareness==='problem-aware').length,356);
assert(icpSeo.every(([,meta])=>meta.icpSegment&&meta.hierarchy&&meta.axis));
assert(icpSeo.some(([,meta])=>meta.hierarchy==='Industry'&&meta.icpSegment==='E-commerce & Retail'));
assert(icpSeo.some(([,meta])=>meta.hierarchy==='Technology'&&meta.icpSegment==='BigQuery'));

const source=fs.readFileSync(new URL('./shared-url-repository.js',import.meta.url),'utf8');
const context=vm.createContext({globalThis:{CompetitiveIntelligenceClassifications:asset},console});
vm.runInContext(source,context);
const repo=context.globalThis.SharedUrlRepository;
const types=[{id:'list',name:'Listicle'},{id:'land',name:'Landing page'},{id:'info',name:'Informational'}];
let n=0;
const root={views:{category:{columns:[],rows:[]},competitor:{columns:[],rows:[]},icp:{columns:[],rows:[]},value:{columns:[],rows:[]}}};
const active={columns:[],rows:[]};
assert.equal(repo.installMappings(root,types,{product:'AI Data Platform',uid:()=>`row-${++n}`,awareness:'problem-aware',contentView:'icp',mode:'seo',activeView:active}),true);
const cells=active.rows.flatMap(row=>Object.values(row.cells||{}));
assert(cells.length>0);
assert(cells.every(cell=>cell.repositoryQueries.length===1));
const urls=cells.flatMap(cell=>repo.resolve(cell.repositoryQueries));
assert.equal(urls.length,repo.query({workspace:'ai-data-platform',awareness:'problem-aware',section:'ICP SEO'}).length);
assert(cells.every(cell=>repo.resolve(cell.repositoryQueries).length===1));
const problemAwareRows=active.rows.filter(row=>row.repositoryWorkspace==='ai-data-platform'&&row.pageGroup==='informational');
assert(problemAwareRows.every(row=>row.repositorySuperHierarchy&&row.repositoryHierarchy));
assert(problemAwareRows.some(row=>row.repositorySuperHierarchy==='Industry'&&row.repositoryHierarchy==='E-commerce & Retail'));
assert(problemAwareRows.some(row=>row.repositorySuperHierarchy==='Technology'&&row.repositoryHierarchy==='BigQuery'));
assert(active.pageColumns.informational.some(column=>column.name==='Data Integration & Ingestion'));
assert(active.pageColumns.informational.some(column=>column.name==='Data Analysis'));

const unaware=structuredClone(active);
assert.equal(repo.installMappings(root,types,{product:'AI Data Platform',uid:()=>`unaware-${++n}`,awareness:'problem-unaware',contentView:'icp',mode:'seo',activeView:unaware}),true);
const unawareCells=unaware.rows.flatMap(row=>Object.values(row.cells||{}));
assert.equal(unawareCells.flatMap(cell=>repo.resolve(cell.repositoryQueries||[])).length,9);
assert.equal(unawareCells.flatMap(cell=>repo.resolve(cell.repositoryQueries||[])).filter(row=>row.awareness==='problem-aware').length,0);
assert(unaware.rows.filter(row=>row.repositoryWorkspace==='ai-data-platform').every(row=>row.repositorySuperHierarchy&&row.repositoryHierarchy));

assert.equal(repo.installMappings(root,types,{product:'AI Data Platform',uid:()=>`solution-${++n}`,awareness:'solution-aware',contentView:'icp',mode:'aeo',activeView:active}),true);
const afterSolution=active.rows.flatMap(row=>Object.values(row.cells||{}));
assert.equal(afterSolution.flatMap(cell=>repo.resolve(cell.repositoryQueries||[])).filter(row=>row.awareness==='problem-aware').length,356);
assert.equal(afterSolution.flatMap(cell=>repo.resolve(cell.repositoryQueries||[])).filter(row=>row.awareness==='solution-aware').length,18);
assert.equal(repo.installMappings(root,types,{product:'AI Data Platform',uid:()=>`return-${++n}`,awareness:'problem-aware',contentView:'icp',mode:'seo',activeView:active}),false);

const seedSource=fs.readFileSync(new URL('./saras-analytics-competitive-intelligence.js',import.meta.url),'utf8');
assert(seedSource.includes("REVISION='saras-analytics-sitemap-2026-10-04-v3'"));
const seedContext=vm.createContext({globalThis:{CompetitiveIntelligenceClassifications:asset},console});
vm.runInContext(seedSource,seedContext);
const importer=seedContext.globalThis.SarasAnalyticsCompetitiveIntelligence;
const positioningTab={positioning:{selectedCategory:'category-1',categories:[{id:'category-1',name:'AI data analytics platform',competitors:[{id:'old-1',name:'Random Company',contentRowId:'old-row'}]}]}};
const strategyRoot={views:{category:{rows:[{id:'category-row',cells:{company:{v:'Random Company'}}}]},competitor:{rows:[{id:'old-row',name:'Random Company',positioningCompetitorId:'old-1'}],types:[{id:'alternatives',name:'Alternatives'}],cells:{'old-row|alternatives':{v:'Random Company alternatives'}}}}};
let strategyId=0;
assert.equal(importer.applyStrategy(positioningTab,strategyRoot,asset,()=>`strategy-${++strategyId}`),true);
const canonical=positioningTab.positioning.categories[0].competitors;
assert.equal(canonical.length,24);
assert.equal(canonical[0].name,'Saras Analytics');
assert(!canonical.some(item=>item.name==='Random Company'));
assert.deepEqual(Array.from(strategyRoot.views.competitor.rows.slice(0,canonical.length),row=>row.name),Array.from(canonical,item=>item.name));
assert.equal(strategyRoot.views.category.rows[0].cells.company,undefined);
const competitorCells=Object.values(strategyRoot.views.competitor.cells);
assert.equal(competitorCells.flatMap(cell=>repo.resolve(cell.repositoryQueries||[])).length,42);
assert(competitorCells.every(cell=>cell.st==='for_review'));
const focal=canonical.find(item=>item.name==='Saras Analytics');
const tripleWhale=canonical.find(item=>item.name==='Triple Whale / Moby AI');
assert(focal&&tripleWhale);
assert.equal(Object.keys(strategyRoot.views.competitor.comparisonCells).length,23);
const focalPair=JSON.stringify([focal.contentRowId,tripleWhale.contentRowId].sort());
assert.equal(strategyRoot.views.competitor.comparisonCells[focalPair].v,'Saras Analytics vs Triple Whale');
assert.equal(strategyRoot.views.competitor.comparisonCells[focalPair].aw,'Competitor aware');
assert.equal(strategyRoot.views.competitor.comparisonCells[focalPair].st,'for_review');
strategyRoot.views.competitor.comparisonCells[focalPair].v='Preserved custom comparison title';
strategyRoot.views.competitor.comparisonCells[focalPair].url='/custom-comparison';
strategyRoot.views.competitor.comparisonCells[focalPair].st='selected';
assert.equal(importer.applyStrategy(positioningTab,strategyRoot,asset,()=>`repeat-${++strategyId}`),false);
assert.equal(strategyRoot.views.competitor.comparisonCells[focalPair].v,'Preserved custom comparison title');
assert.equal(strategyRoot.views.competitor.comparisonCells[focalPair].url,'/custom-comparison');
assert.equal(strategyRoot.views.competitor.comparisonCells[focalPair].st,'selected');
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
assert(html.includes('<script src="saras-analytics-competitive-intelligence.js"></script>'));
assert(html.includes('await ensureSarasAnalyticsCompetitiveIntelligenceSeed();'));
console.log('PASS: all 770 Saras Analytics sitemap URLs are scoped to AI Data Platform and every keyword cell resolves one article.');
