import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const asset=JSON.parse(fs.readFileSync(new URL('./competitive-intelligence-classifications.json',import.meta.url),'utf8'));
const source=fs.readFileSync(new URL('./shared-url-repository.js',import.meta.url),'utf8');
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const context=vm.createContext({globalThis:{CompetitiveIntelligenceClassifications:asset},console});vm.runInContext(source,context);
const repo=context.globalThis.SharedUrlRepository;
assert.equal(repo.records().length,7880);
assert.equal(repo.query({section:'Value AEO'}).length,178);
assert.equal(repo.query({section:'Value SEO'}).length,2813);
const root={views:{category:{columns:[],rows:[]},icp:{columns:[],rows:[]},value:{columns:[],rows:[]}}};let n=0;
const types=[{id:'list',name:'Listicle'},{id:'land',name:'Landing page'},{id:'info',name:'Informational'}];
assert.equal(repo.installMappings(root,types,{product:'Answer Engine Optimization Agency',uid:()=>'row-'+(++n)}),true);
assert.equal(repo.installMappings(root,types,{product:'Answer Engine Optimization Agency',uid:()=>'row-'+(++n)}),false);
const cells=Object.values(root.views).flatMap(view=>(view.rows||[]).flatMap(row=>Object.values(row.cells||{})));
assert(cells.length>0);assert(cells.every(cell=>cell.repositoryQueries?.length));
const linkedUrls=cells.flatMap(cell=>repo.resolve(cell.repositoryQueries));
assert.equal(new Set(linkedUrls.map(row=>row.url)).size,5399);
assert(root.views.value.rows.filter(row=>row.pageGroup==='matrix').every(row=>Object.values(row.cells).every(cell=>cell.mode==='aeo')));
assert(root.views.value.rows.filter(row=>row.pageGroup==='informational').every(row=>Object.values(row.cells).every(cell=>cell.mode==='seo')));
const aliasRoot={views:{category:{columns:[],pageColumns:{listicle:[{id:'existing-category',name:'Category Names'}]},rows:[{id:'blank',pageGroup:'listicle',cells:{}}]},icp:{columns:[],rows:[]},value:{columns:[],rows:[]}},sharedUrlRepositoryRevision:'old:existing-cells-v1'};
assert.equal(repo.installMappings(aliasRoot,types,{product:'Answer Engine Optimization Agency',uid:()=>'alias-'+(++n)}),true);
assert(aliasRoot.views.category.rows.find(row=>row.pageGroup==='listicle'&&row.repositoryHierarchy).cells['existing-category']?.repositoryQueries?.length);
assert.equal(aliasRoot.views.category.pageColumns.listicle.some(column=>column.id==='shared-url-col-category-listicle-category-name'),false);
assert(!html.includes('Corporate & Non-SEO\', noun: \'URL\', kind: \'shared'));
assert(!html.includes('shared-keyword-urls'));
assert(html.includes('SharedUrlRepository?.resolve(o.get().repositoryQueries)'));
assert(html.includes("'+ URL (' + importedUrlCount + ')'"));
console.log('PASS: all 5,399 classified SEO/AEO URLs resolve inside existing keyword cells without duplicating full URLs in board state.');
