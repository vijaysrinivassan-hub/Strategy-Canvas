import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const asset=JSON.parse(fs.readFileSync(new URL('./competitive-intelligence-classifications.json',import.meta.url),'utf8'));
const source=fs.readFileSync(new URL('./shared-url-repository.js',import.meta.url),'utf8');
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const context=vm.createContext({globalThis:{CompetitiveIntelligenceClassifications:asset},console});
vm.runInContext(source,context);
const repo=context.globalThis.SharedUrlRepository;
assert.equal(repo.records().length,7880);
assert.equal(repo.query({view:'category',mode:'aeo'}).length,321);
assert.equal(repo.query({view:'icp',mode:'aeo'}).length,663);
assert.equal(repo.query({view:'value',mode:'aeo'}).length,178);
assert.equal(repo.query({view:'category',mode:'seo'}).length,642);
assert.equal(repo.query({view:'icp',mode:'seo'}).length,782);
assert.equal(repo.query({view:'value',mode:'seo'}).length,2813);
assert.equal(repo.query({view:'nonseo',mode:'nonseo'}).length,2481);
assert(repo.query({view:'value',mode:'aeo'}).every(row=>row.pageType==='Listicle'||row.pageType==='Landing Page'));
assert(repo.query({view:'value',mode:'seo'}).every(row=>row.pageType==='Informational'));
assert.equal(repo.records().find(row=>row.url==='https://graphite.io/aeo').competitor,'Graphite');
assert(html.includes("{ id: 'nonseo', label: 'Corporate & Non-SEO'"));
assert(html.includes('SharedUrlRepository?.render'));
assert(html.includes('shared-url-repository.js'));
console.log('PASS: one 7,880-URL repository powers Category, ICP, Value, Corporate/Non-SEO and channel-correct AEO/SEO views.');
